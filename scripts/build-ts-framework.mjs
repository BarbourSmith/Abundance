#!/usr/bin/env node
/**
 * Build script for the TypeScript Code atom framework.
 *
 * Reads:  src/worker/ts-framework.ts
 * Writes: src/worker/generated/ts-framework.generated.js   (runtime sandbox)
 *         src/worker/generated/ts-framework.generated.d.ts  (Monaco types)
 *
 * Usage:
 *   node scripts/build-ts-framework.mjs
 *   npm run build:ts-framework
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "fs";
import { execSync } from "child_process";
import { fileURLToPath } from "url";
import path from "path";
import os from "os";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const SRC = path.join(ROOT, "src/worker/ts-framework.ts");
const OUT_DIR = path.join(ROOT, "src/worker/generated");

const GENERATED_HEADER = (filename) =>
  `// AUTO-GENERATED by scripts/build-ts-framework.mjs from src/worker/ts-framework.ts\n` +
  `// Do not edit directly — run \`npm run build:ts-framework\`.\n`;

// ---------------------------------------------------------------------------
// 1. Runtime JS — strip TypeScript type annotations with esbuild
// ---------------------------------------------------------------------------
console.log("Building runtime JS…");
const { transform } = await import("esbuild");

const tsSource = readFileSync(SRC, "utf-8");
const { code: jsCode } = await transform(tsSource, {
  loader: "ts",
  target: "es2020",
  // No bundling, no module format — we want bare class/function declarations
  // that can be prepended directly into the sandbox Function body.
  format: "esm",
});

// esbuild emits `export class`/`export function` for each exported decl.
// Strip the `export` keyword so we get bare top-level declarations that
// reference `replicad` lexically. We then wrap the whole body in a factory
// function so both consumers can supply their own `replicad`:
//
//   - Worker code imports `makeAbundanceFramework` and calls it with the
//     worker's replicad module to obtain { Assembly, __promoteInput }.
//   - The sandbox preamble inlines this file as raw text and immediately
//     calls `makeAbundanceFramework(replicad)` to bind the same names in
//     module scope (where `replicad` came from globalThis context).
const cleanedBody = jsCode
  .replace(/^export\s+(class|function|const|let|var)\s/gm, "$1 ")
  .replace(/^export\s*\{[^}]*\};?\s*$/gm, "")
  .trimEnd();

const factoryJs =
  `export function makeAbundanceFramework(replicad) {\n` +
  cleanedBody
    .split("\n")
    .map((line) => (line.length ? "  " + line : ""))
    .join("\n") +
  `\n  return { Assembly, __promoteInput };\n` +
  `}\n`;

if (!existsSync(OUT_DIR)) mkdirSync(OUT_DIR, { recursive: true });

writeFileSync(
  path.join(OUT_DIR, "ts-framework.generated.js"),
  GENERATED_HEADER("ts-framework.generated.js") + "\n" + factoryJs,
);
console.log("  ✓ ts-framework.generated.js");

// ---------------------------------------------------------------------------
// 2. Declaration file — use tsc to emit .d.ts, then post-process for Monaco
// ---------------------------------------------------------------------------
console.log("Building .d.ts…");

// Write a temporary tsconfig so we can run tsc on just the framework file.
const tmpDir = os.tmpdir();
const tmpTsConfig = path.join(tmpDir, "abundance-fw-tsconfig.json");
const tmpOutDir = path.join(tmpDir, "abundance-fw-out");

writeFileSync(
  tmpTsConfig,
  JSON.stringify({
    compilerOptions: {
      target: "ES2020",
      module: "ESNext",
      moduleResolution: "bundler",
      declaration: true,
      emitDeclarationOnly: true,
      outDir: tmpOutDir,
      rootDir: path.dirname(SRC),
      strict: true,
      skipLibCheck: true,
      // Treat `replicad` as an ambient global so tsc doesn't complain that
      // it's undeclared. The generated .d.ts will provide proper typing.
      noImplicitAny: false,
    },
    include: [SRC],
  }),
);

execSync(`npx tsc --project ${tmpTsConfig}`, { stdio: "inherit", cwd: ROOT });

// tsc with a single input file + outDir emits directly to the outDir root.
const emittedDts = readFileSync(
  path.join(tmpOutDir, "ts-framework.d.ts"),
  "utf-8",
);

// Post-process the raw tsc output into Monaco-friendly ambient global form:
//
//  1. Replace `export declare class Foo` → `class Foo` (strip export/declare)
//  2. Replace `export declare function` → `function`
//  3. Wrap everything (except the trailing `export {}`) in `declare global {}`
//  4. Prepend the `import * as _replicad` + replace `any` plane/geometry types
//     with proper replicad types for the best IntelliSense experience.

// Strip tsc's module boilerplate lines
let dts = emittedDts
  // Remove "export declare" modifiers — we want globals, not module exports
  .replace(/^export declare /gm, "")
  // Remove the trailing bare `export {};` that tsc emits for modules
  .replace(/^export\s*\{\s*\};\s*$/m, "")
  // Strip the `declare ` prefix from standalone declarations (tsc adds these
  // for non-exported items in a module context)
  .replace(/^declare (class|function|const|let|var|type) /gm, "$1 ")
  .trimEnd();

// Replace the `any` types that come from our `declare const replicad: any`
// shortcut with proper replicad types so Monaco shows real completions.
//
// `Assembly` is generic over the type of its `geometry` field. In source
// the bound is `any`; here we widen the parameter to a real bound using
// the `LeafGeom` / `AnyGeom` aliases injected into the global block below.
dts = dts
  // plane: any → plane: _replicad.Plane
  .replace(/\bplane: any\b/g, "plane: _replicad.Plane")
  // Accessor signatures: `get geometry(): any;` / `set geometry(value: any);`
  // → use the generic parameter `G` so callers see a proper replicad union.
  .replace(/\bget geometry\(\): any;/g, "get geometry(): G;")
  .replace(/\bset geometry\(value: any\);/g, "set geometry(value: G);")
  // Legacy field form `geometry: any` (kept for safety in case the source
  // ever reverts to a plain field).
  .replace(/\bgeometry: any\b/g, "geometry: G")
  // Class header: add a real bound + default to the generic parameter.
  .replace(
    /class Assembly<G = any>/g,
    "class Assembly<G extends AnyGeom = AnyGeom>",
  )
  // Replace every `Assembly<any>` (iterator return, isLeaf guard, onLeafs
  // callback param/return) with `Assembly<LeafGeom>` so `leaf.geometry`
  // narrows to the proper replicad union without any user-side checks.
  .replace(/\bAssembly<any>/g, "Assembly<LeafGeom>")
  // is2D / is3D / isWire / isPoint: turn boolean returns into proper
  // type-narrowing guards so user code can read `.geometry` as the
  // appropriate replicad type without a manual cast.
  .replace(
    /is2D\(\): boolean;/g,
    "is2D(): this is Assembly<_replicad.Drawing>;",
  )
  .replace(
    /is3D\(\): boolean;/g,
    "is3D(): this is Assembly<_replicad.AnyShape>;",
  )
  .replace(
    /isWire\(\): boolean;/g,
    "isWire(): this is Assembly<_replicad.Wire>;",
  )
  .replace(
    /isPoint\(\): boolean;/g,
    "isPoint(): this is Assembly<_replicad.Vertex>;",
  );

// Build the final .d.ts: import + declare global wrapper, then a real
// module-level export so worker-side code can `import { makeAbundanceFramework }`
// with proper types. The factory is intentionally NOT inside the `declare
// global` block — Monaco only exposes globals to user code, so users won't
// see this internal symbol in their atom autocomplete.
const finalDts =
  GENERATED_HEADER("ts-framework.generated.d.ts") +
  `\nimport * as _replicad from "replicad";\n` +
  `\ndeclare global {\n` +
  `  const replicad: typeof _replicad;\n` +
  `\n` +
  `  namespace replicad {\n` +
  `    type AnyShape = _replicad.AnyShape;\n` +
  `    type Shape3D = _replicad.Shape3D;\n` +
  `    type Drawing = _replicad.Drawing;\n` +
  `    type Plane = _replicad.Plane;\n` +
  `    type Sketch = _replicad.Sketch;\n` +
  `    type Sketches = _replicad.Sketches;\n` +
  `    type Wire = _replicad.Wire;\n` +
  `    type Vertex = _replicad.Vertex;\n` +
  `    type Face = _replicad.Face;\n` +
  `    type Solid = _replicad.Solid;\n` +
  `    type Shape<T> = _replicad.Shape<T>;\n` +
  `    type Vector = _replicad.Vector;\n` +
  `    type Point = _replicad.Point;\n` +
  `    type BoundingBox = _replicad.BoundingBox;\n` +
  `    type BoundingBox2d = _replicad.BoundingBox2d;\n` +
  `    type Finder = _replicad.Finder;\n` +
  `  }\n` +
  `\n` +
  `  /** Geometry type for a *leaf* Assembly (no children). */\n` +
  `  type LeafGeom = _replicad.AnyShape | _replicad.Drawing;\n` +
  `\n` +
  `  /** Geometry type for any Assembly node \u2014 either a leaf or a branch. */\n` +
  `  type AnyGeom = LeafGeom | Assembly[];\n` +
  `\n` +
  // Indent the tsc-emitted class/function declarations inside the global block
  dts
    .split("\n")
    .map((line) => (line.trim() ? "  " + line : ""))
    .join("\n") +
  `\n}\n` +
  `\n` +
  `/**\n` +
  ` * Build the Abundance TS-framework runtime (Assembly class + internal\n` +
  ` * promotion helper) bound to a specific replicad instance. Used by the\n` +
  ` * worker to obtain class references that share identity with the worker's\n` +
  ` * replicad WASM module. The sandbox preamble calls the same factory with\n` +
  ` * its own injected replicad reference.\n` +
  ` */\n` +
  `export function makeAbundanceFramework(replicad: typeof _replicad): {\n` +
  `  Assembly: typeof globalThis.Assembly;\n` +
  `  __promoteInput: (value: any) => any;\n` +
  `};\n`;

writeFileSync(path.join(OUT_DIR, "ts-framework.generated.d.ts"), finalDts);
console.log("  ✓ ts-framework.generated.d.ts");

console.log("\nDone. Commit both generated files alongside ts-framework.ts.");
